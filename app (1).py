
import streamlit as st
import pandas as pd
import joblib

# Load trained model
model = joblib.load("car_price_model.pkl")

# Page configuration
st.set_page_config(
    page_title="Car Price Prediction",
    page_icon="🚗",
    layout="centered"
)

# Application heading
st.title("🚗 Car Price Prediction")
st.write(
    "Predict the estimated selling price of a used car "
    "using Multiple Linear Regression."
)

st.divider()

# User input form
st.subheader("Enter Car Details")

with st.form("car_prediction_form"):

    col1, col2 = st.columns(2)

    with col1:
        year = st.number_input(
            "Manufacturing Year",
            min_value=1990,
            max_value=2026,
            value=2018
        )

        km_driven = st.number_input(
            "Kilometres Driven",
            min_value=0,
            value=45000
        )

        fuel = st.selectbox(
            "Fuel Type",
            ["Petrol", "Diesel", "CNG", "LPG", "Electric"]
        )

        seller_type = st.selectbox(
            "Seller Type",
            ["Individual", "Dealer", "Trustmark Dealer"]
        )

        transmission = st.selectbox(
            "Transmission",
            ["Manual", "Automatic"]
        )

    with col2:
        owner = st.selectbox(
            "Previous Owner",
            [
                "First Owner",
                "Second Owner",
                "Third Owner",
                "Fourth & Above Owner",
                "Test Drive Car"
            ]
        )

        mileage = st.number_input(
            "Mileage (kmpl)",
            min_value=0.0,
            value=20.0
        )

        engine = st.number_input(
            "Engine Capacity (CC)",
            min_value=0.0,
            value=1197.0
        )

        max_power = st.number_input(
            "Maximum Power (bhp)",
            min_value=0.0,
            value=82.0
        )

        seats = st.number_input(
            "Number of Seats",
            min_value=2,
            max_value=10,
            value=5
        )

    submitted = st.form_submit_button(
        "Predict Car Price",
        use_container_width=True
    )

# Prediction
if submitted:

    input_data = pd.DataFrame([{
        'year': year,
        'km_driven': km_driven,
        'fuel': fuel,
        'seller_type': seller_type,
        'transmission': transmission,
        'owner': owner,
        'mileage': mileage,
        'engine': engine,
        'max_power': max_power,
        'seats': seats
    }])

    prediction = model.predict(input_data)[0]

    st.divider()

    st.success("Car Price Prediction Completed!")

    st.metric(
        label="Estimated Selling Price",
        value=f"₹ {prediction:,.2f}"
    )

    st.caption(
        "Note: This is an estimated price generated by a "
        "machine learning model, not a guaranteed market value."
    )

st.divider()

st.write("Developed using Python, Streamlit and Multiple Linear Regression.")
